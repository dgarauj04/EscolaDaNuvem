# Calculadora de volume

comprimento = 12
largura = 14
altura = 20
volume = comprimento * largura * altura
print(f"O volume da caixa é {volume} cm³")
# ou pode ser feito da seguinte forma:
print(f"Dada as seguintes dimensões: comprimento = {comprimento} cm, largura = {largura} cm e altura = {altura}cm, o volume da caixa é {comprimento * largura * altura} cm³")