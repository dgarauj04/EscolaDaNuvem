# Calculadora preço total

produto = "Cadeira Infantil"
preco = 12.40
quantidade = 3
total = preco * quantidade
print(f"O preço total do produto {produto} com {quantidade} unidades e de R${preco} reais, fica R${total} reais")
# ou pode fazer da seguinte forma:
print(f"O preço total do produto {produto} com {quantidade} unidades e de R${preco} reais, fica R${preco * quantidade} reais")